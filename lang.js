const langToggleBtn = document.getElementById('lang-toggle');

// Itt történik a varázslat: 
// 1. Megnézzük, van-e már mentett nyelv a localStorage-ban.
// 2. Ha nincs, megnézzük a bönyésző nyelvét (navigator.language). Ha az magyarral kezdődik ('hu'), akkor 'hu', egyébként alapból 'en'.
let currentLang = localStorage.getItem('portfolio-lang') ||
    (navigator.language.toLowerCase().startsWith('hu') ? 'hu' : 'en');

function applyLanguage(lang) {
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // A gomb mindig azt mutatja, amire át lehet váltani
    langToggleBtn.textContent = lang === 'hu' ? 'EN' : 'HU';
    localStorage.setItem('portfolio-lang', lang);
    currentLang = lang;
}

// Kezdeti nyelv beállítása betöltéskor
applyLanguage(currentLang);

// Kattintás esemény a váltáshoz
langToggleBtn.addEventListener('click', () => {
    const nextLang = currentLang === 'hu' ? 'en' : 'hu';
    applyLanguage(nextLang);
});